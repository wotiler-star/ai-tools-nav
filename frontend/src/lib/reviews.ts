/**
 * 找出与某个工具相关的原创文章（用于 /tool/[id] 详情页的「相关评测」内链）。
 *
 * 匹配策略（从强到弱，刻意保守，避免满屏都是不相关内容）：
 * 1. 文章标题或摘要里出现了工具名
 * 2. 文章标签与工具名完全一致
 * 3. 文章标签与工具的某个标签完全一致
 *
 * 只做「完全一致」匹配，不做子串包含 —— 否则短标签（如 AI）会命中几乎所有工具。
 */
export function getRelatedReviews(
  toolName: string,
  toolTags: string[] = [],
  limit = 3
): ReviewItem[] {
  const name = (toolName || "").trim().toLowerCase();
  const tags = (toolTags || [])
    .map((t) => (t || "").trim().toLowerCase())
    .filter(Boolean);

  if (!name && tags.length === 0) return [];

  const scored = REVIEWS.map((r) => {
    const rTags = r.tags.map((t) => (t || "").trim().toLowerCase());
    let score = 0;

    // 1. 标题/摘要命中工具名（要求名字有一定长度，避免误命中）
    if (name.length >= 3) {
      const title = r.title.toLowerCase();
      const summary = r.summary.toLowerCase();
      if (title.includes(name)) score += 3;
      else if (summary.includes(name)) score += 2;
    }
    // 2. 文章标签 === 工具名
    if (name && rTags.includes(name)) score += 3;
    // 3. 文章标签 === 工具标签
    if (tags.length && rTags.some((rt) => tags.includes(rt))) score += 2;

    return { r, score };
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score);

  return scored.slice(0, limit).map((x) => x.r);
}
